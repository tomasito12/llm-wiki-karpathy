"""Read-only artifact retention inventory for wiki operations."""

from __future__ import annotations

import os
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Literal

from src.wiki_paths.config import WikiPaths

DataClass = Literal["canonical", "generated", "temporary"]
CLEANUP_BLOCKED_REASON = (
    "real cleanup requires hatch run wiki-cleanup --after-release <release_id> --yes"
)


@dataclass(frozen=True)
class ArtifactAreaDefinition:
    """Static metadata for one managed artifact area."""

    key: str
    path: Path
    data_class: DataClass
    purpose: str
    cleanup_policy: str
    must_backup: bool
    git_policy: str
    optional: bool = False


@dataclass(frozen=True)
class ArtifactAreaStatus:
    """Filesystem inventory for one artifact area."""

    key: str
    path: Path
    data_class: DataClass
    purpose: str
    cleanup_policy: str
    must_backup: bool
    git_policy: str
    exists: bool
    file_count: int
    byte_count: int
    newest_mtime: float | None
    oldest_mtime: float | None
    warnings: list[str]

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serializable area status payload."""
        payload = asdict(self)
        payload["path"] = str(self.path)
        return payload


@dataclass(frozen=True)
class CleanupPreflight:
    """Read-only cleanup preflight summary."""

    temporary_file_count: int
    temporary_byte_count: int
    cleanup_candidate_count: int
    cleanup_candidate_bytes: int
    cleanup_blocked_reason: str

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serializable cleanup preflight payload."""
        return asdict(self)


@dataclass(frozen=True)
class RetentionInventory:
    """Full artifact retention inventory."""

    areas: list[ArtifactAreaStatus]
    totals_by_class: dict[str, dict[str, int]]
    cleanup_preflight: CleanupPreflight
    warnings: list[str]

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serializable retention inventory payload."""
        return {
            "areas": [area.to_dict() for area in self.areas],
            "totals_by_class": self.totals_by_class,
            "cleanup_preflight": self.cleanup_preflight.to_dict(),
            "warnings": list(self.warnings),
        }


