def collect_retention_inventory(paths: WikiPaths) -> RetentionInventory:
    """Collect a read-only artifact retention inventory."""
    areas = [inventory_area(definition) for definition in artifact_area_definitions(paths)]
    warnings = _collect_inventory_warnings(areas)
    totals_by_class = _totals_by_class(areas)
    cleanup_preflight = _build_cleanup_preflight(areas)
    return RetentionInventory(
        areas=areas,
        totals_by_class=totals_by_class,
        cleanup_preflight=cleanup_preflight,
        warnings=warnings,
    )


def inventory_area(definition: ArtifactAreaDefinition) -> ArtifactAreaStatus:
    """Inventory one artifact area using read-only filesystem metadata."""
    stats = _path_inventory_stats(definition.path)
    warnings: list[str] = []
    if definition.data_class == "canonical" and not stats.exists and not definition.optional:
        warnings.append(f"Canonical path missing: {definition.key}.")
    return ArtifactAreaStatus(
        key=definition.key,
        path=definition.path,
        data_class=definition.data_class,
        purpose=definition.purpose,
        cleanup_policy=definition.cleanup_policy,
        must_backup=definition.must_backup,
        git_policy=definition.git_policy,
        exists=stats.exists,
        file_count=stats.file_count,
        byte_count=stats.byte_count,
        newest_mtime=stats.newest_mtime,
        oldest_mtime=stats.oldest_mtime,
        warnings=warnings,
    )


def build_retention_recommendations(inventory: RetentionInventory) -> list[str]:
    """Return conservative recommendations derived from retention inventory."""
    recommendations: list[str] = []
    if inventory.cleanup_preflight.temporary_file_count > 0:
        recommendations.append(
            "Temporary artifacts are present; inspect cleanup candidates with "
            "`hatch run wiki-cleanup --dry-run` after a release manifest exists.",
        )
    for warning in inventory.warnings:
        if warning.startswith("Canonical path missing:"):
            recommendations.append(f"{warning} Verify path configuration before continuing.")
    return recommendations


def format_retention_text(inventory: RetentionInventory) -> str:
    """Render a concise human-readable retention inventory section."""
    lines = ["Retention Inventory"]
    for data_class in ("canonical", "generated", "temporary"):
        totals = inventory.totals_by_class.get(data_class, {"areas": 0, "files": 0, "bytes": 0})
        lines.append(
            f"- {data_class}: {totals['areas']} areas, {totals['files']} files, "
            f"{_format_bytes(totals['bytes'])}"
        )
    preflight = inventory.cleanup_preflight
    if preflight.temporary_file_count:
        lines.append(
            f"- cleanup preflight: temporary artifacts present; {preflight.cleanup_blocked_reason}"
        )
    else:
        lines.append(
            f"- cleanup preflight: no temporary artifacts present; "
            f"{preflight.cleanup_blocked_reason}"
        )
    lines.append("")
    lines.append("Areas")
    for area in inventory.areas:
        presence = "present" if area.exists else "missing"
        lines.append(
            f"- {area.key}: {area.data_class}, {presence}, {area.file_count} files, "
            f"{area.cleanup_policy}"
        )
    if inventory.warnings:
        lines.append("")
        lines.append("Retention warnings")
        lines.extend(f"- {warning}" for warning in inventory.warnings)
    return "\n".join(lines)


@dataclass(frozen=True)
class _PathInventoryStats:
    """Filesystem stats for one inventoried path."""

    exists: bool
    file_count: int
    byte_count: int
    newest_mtime: float | None
    oldest_mtime: float | None


def _path_inventory_stats(path: Path) -> _PathInventoryStats:
    """Count files and bytes for a path without following symlinked directories."""
    if not path.exists():
        return _PathInventoryStats(
            exists=False,
            file_count=0,
            byte_count=0,
            newest_mtime=None,
            oldest_mtime=None,
        )
    if path.is_file():
        stat = path.stat()
        mtime = stat.st_mtime
        return _PathInventoryStats(
            exists=True,
            file_count=1,
            byte_count=stat.st_size,
            newest_mtime=mtime,
            oldest_mtime=mtime,
        )
    if not path.is_dir():
        return _PathInventoryStats(
            exists=True,
            file_count=0,
            byte_count=0,
            newest_mtime=None,
            oldest_mtime=None,
        )
    file_count = 0
    byte_count = 0
    newest_mtime: float | None = None
    oldest_mtime: float | None = None
    for root, dirnames, filenames in os.walk(path, followlinks=False):
        root_path = Path(root)
        dirnames[:] = [name for name in dirnames if not (root_path / name).is_symlink()]
        for filename in filenames:
            file_path = root_path / filename
            if file_path.is_symlink():
                continue
            try:
                stat = file_path.stat()
            except OSError:
                continue
            file_count += 1
            byte_count += stat.st_size
            newest_mtime = (
                stat.st_mtime if newest_mtime is None else max(newest_mtime, stat.st_mtime)
            )
            oldest_mtime = (
                stat.st_mtime if oldest_mtime is None else min(oldest_mtime, stat.st_mtime)
            )
    return _PathInventoryStats(
        exists=True,
        file_count=file_count,
        byte_count=byte_count,
        newest_mtime=newest_mtime,
        oldest_mtime=oldest_mtime,
    )


def _totals_by_class(areas: list[ArtifactAreaStatus]) -> dict[str, dict[str, int]]:
    """Aggregate file and byte totals by data class."""
    totals: dict[str, dict[str, int]] = {
        "canonical": {"areas": 0, "files": 0, "bytes": 0},
        "generated": {"areas": 0, "files": 0, "bytes": 0},
        "temporary": {"areas": 0, "files": 0, "bytes": 0},
    }
    for area in areas:
        bucket = totals[area.data_class]
        if area.exists:
            bucket["areas"] += 1
        bucket["files"] += area.file_count
        bucket["bytes"] += area.byte_count
    return totals


def _build_cleanup_preflight(areas: list[ArtifactAreaStatus]) -> CleanupPreflight:
    """Build read-only cleanup preflight information."""
    temporary_areas = [area for area in areas if area.data_class == "temporary"]
    temporary_file_count = sum(area.file_count for area in temporary_areas)
    temporary_byte_count = sum(area.byte_count for area in temporary_areas)
    return CleanupPreflight(
        temporary_file_count=temporary_file_count,
        temporary_byte_count=temporary_byte_count,
        cleanup_candidate_count=0,
        cleanup_candidate_bytes=0,
        cleanup_blocked_reason=CLEANUP_BLOCKED_REASON,
    )


def _collect_inventory_warnings(areas: list[ArtifactAreaStatus]) -> list[str]:
    """Collect top-level retention warnings."""
    warnings: list[str] = []
    for area in areas:
        warnings.extend(area.warnings)
    return warnings


def _format_bytes(byte_count: int) -> str:
    """Format a byte count for human-readable output."""
    if byte_count < 1024:
        return f"{byte_count} B"
    if byte_count < 1024 * 1024:
        return f"{byte_count / 1024:.1f} KB"
    if byte_count < 1024 * 1024 * 1024:
        return f"{byte_count / (1024 * 1024):.1f} MB"
    return f"{byte_count / (1024 * 1024 * 1024):.1f} GB"
